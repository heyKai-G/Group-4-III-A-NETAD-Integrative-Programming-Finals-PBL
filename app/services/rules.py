"""Generate Suricata's local.rules file from the wizard settings.

Suricata does the heavy lifting (it reads these rules plus the Emerging Threats
Open rule set). Thresholds scale with the sensitivity chosen in the wizard.

Rule messages follow the pattern  LAB-IDS [Category] text  so the dashboard can
categorise them without guessing.
"""
import os

# sensitivity -> thresholds
THRESHOLDS = {
    "low": {
        "conn_burst": 12, "fail_resp": 8, "http_login": 12,
        "syn_flood": 3000, "udp_flood": 3000, "icmp_flood": 1000, "odd_flags": 8,
    },
    "medium": {
        "conn_burst": 8, "fail_resp": 5, "http_login": 8,
        "syn_flood": 1500, "udp_flood": 1500, "icmp_flood": 500, "odd_flags": 4,
    },
    "high": {
        "conn_burst": 5, "fail_resp": 3, "http_login": 5,
        "syn_flood": 800, "udp_flood": 800, "icmp_flood": 250, "odd_flags": 2,
    },
}

# Rules where the attacker is the *destination* of the matching packet
# (we match the server's "login failed" reply). The importer swaps src/dst.
REVERSED_SIDS = {9000010, 9000011, 9000012}

SID_BASE = 9000000

# NOTE (verified with Suricata 7.0.3): a payload-only rule alerts once per TCP connection
# unless it carries "dsize:>0"; with it, every matching packet counts toward the threshold.
# A rule with only addresses/ports (no other keyword) is "IP-only": Suricata evaluates it once
# per flow, so flood rules always carry a per-packet keyword (flow, flags, itype).
# Thresholds are fixed time windows, so a flood that straddles a window boundary can be
# counted in two halves.


def build_rules(sensitivity="medium"):
    t = THRESHOLDS.get(sensitivity, THRESHOLDS["medium"])
    cb, fr, hl = t["conn_burst"], t["fail_resp"], t["http_login"]
    rules = [
        "# Lab IDS local rules - generated by the web app. Do not edit by hand;",
        "# change the settings in the web app instead (they overwrite this file).",
        f"# Sensitivity: {sensitivity}",
        "",
        "# ---- Brute force: bursts of new connections to login services ----",
        f'alert tcp any any -> $HOME_NET 22 (msg:"LAB-IDS [Brute Force] SSH connection burst from one source"; flow:to_server; flags:S,12; threshold:type both, track by_src, count {cb}, seconds 60; classtype:attempted-admin; sid:9000001; rev:1;)',
        f'alert tcp any any -> $HOME_NET 21 (msg:"LAB-IDS [Brute Force] FTP connection burst from one source"; flow:to_server; flags:S,12; threshold:type both, track by_src, count {cb}, seconds 60; classtype:attempted-admin; sid:9000002; rev:1;)',
        f'alert tcp any any -> $HOME_NET 23 (msg:"LAB-IDS [Brute Force] Telnet connection burst from one source"; flow:to_server; flags:S,12; threshold:type both, track by_src, count {cb}, seconds 60; classtype:attempted-admin; sid:9000003; rev:1;)',
        f'alert tcp any any -> $HOME_NET 3389 (msg:"LAB-IDS [Brute Force] RDP connection burst from one source"; flow:to_server; flags:S,12; threshold:type both, track by_src, count {cb}, seconds 60; classtype:attempted-admin; sid:9000004; rev:1;)',
        "",
        "# ---- Brute force: failed-login replies from the server ----",
        f'alert tcp $HOME_NET 21 -> any any (msg:"LAB-IDS [Brute Force] FTP repeated failed logins"; flow:established,to_client; dsize:>0; content:"530 "; depth:4; threshold:type both, track by_dst, count {fr}, seconds 60; classtype:attempted-admin; sid:9000010; rev:1;)',
        f'alert tcp $HOME_NET 23 -> any any (msg:"LAB-IDS [Brute Force] Telnet repeated failed logins"; flow:established,to_client; dsize:>0; content:"Login incorrect"; nocase; threshold:type both, track by_dst, count {fr}, seconds 60; classtype:attempted-admin; sid:9000011; rev:1;)',
        f'alert http $HOME_NET any -> any any (msg:"LAB-IDS [Brute Force] HTTP repeated 401 Unauthorized replies"; flow:established,to_client; http.stat_code; content:"401"; threshold:type both, track by_dst, count {fr}, seconds 60; classtype:attempted-admin; sid:9000012; rev:1;)',
        f'alert http any any -> $HOME_NET any (msg:"LAB-IDS [Brute Force] HTTP repeated login form submissions"; flow:established,to_server; http.method; content:"POST"; http.uri; content:"login"; nocase; threshold:type both, track by_src, count {hl}, seconds 60; classtype:attempted-admin; sid:9000014; rev:1;)',
        "",
        "# ---- Scans using unusual TCP flags ----",
        f'alert tcp any any -> $HOME_NET any (msg:"LAB-IDS [Port Scan] TCP Xmas scan (FIN+PSH+URG)"; flags:FPU,12; threshold:type both, track by_src, count {t["odd_flags"]}, seconds 10; classtype:attempted-recon; sid:9000020; rev:1;)',
        f'alert tcp any any -> $HOME_NET any (msg:"LAB-IDS [Port Scan] TCP NULL scan (no flags)"; flags:0; threshold:type both, track by_src, count {t["odd_flags"]}, seconds 10; classtype:attempted-recon; sid:9000021; rev:1;)',
        f'alert tcp any any -> $HOME_NET any (msg:"LAB-IDS [Port Scan] TCP FIN scan"; flags:F,12; threshold:type both, track by_src, count {t["odd_flags"]}, seconds 10; classtype:attempted-recon; sid:9000022; rev:1;)',
        "",
        "# ---- Floods (counted per victim, so distributed floods are caught too) ----",
        f'alert tcp any any -> $HOME_NET any (msg:"LAB-IDS [DDoS] SYN flood"; flags:S,12; threshold:type both, track by_dst, count {t["syn_flood"]}, seconds 5; classtype:attempted-dos; sid:9000030; rev:1;)',
        f'alert udp any any -> $HOME_NET any (msg:"LAB-IDS [DDoS] UDP flood"; flow:to_server; threshold:type both, track by_dst, count {t["udp_flood"]}, seconds 5; classtype:attempted-dos; sid:9000031; rev:1;)',
        f'alert icmp any any -> $HOME_NET any (msg:"LAB-IDS [DDoS] ICMP echo flood"; itype:8; threshold:type both, track by_dst, count {t["icmp_flood"]}, seconds 5; classtype:attempted-dos; sid:9000032; rev:1;)',
        "",
        "# ---- Malware indicators ----",
        '# Matches only part of the standard EICAR antivirus test string, so antivirus',
        '# software does not quarantine this rules file.',
        'alert http any any -> any any (msg:"LAB-IDS [Malware/C2] EICAR antivirus test file transferred"; flow:established,to_client; file_data; content:"EICAR-STANDARD-ANTIVIRUS-TEST-FILE"; classtype:trojan-activity; sid:9000040; rev:1;)',
        'alert tcp $HOME_NET any -> any [4444,31337,1337,6667,6697] (msg:"LAB-IDS [Malware/C2] Outbound connection to a common reverse-shell / IRC botnet port"; flow:to_server; flags:S,12; threshold:type limit, track by_src, count 1, seconds 60; classtype:trojan-activity; sid:9000041; rev:1;)',
        "",
    ]
    return "\n".join(rules)


def write_local_rules(path, sensitivity):
    folder = os.path.dirname(os.path.abspath(path))
    os.makedirs(folder, exist_ok=True)
    text = build_rules(sensitivity)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return path
